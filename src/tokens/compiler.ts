import { tokens, type DesignTokens } from "./tokens";

/**
 * Compiles TypeScript design tokens into Tailwind CSS v4 compatible CSS.
 * Outputs:
 * - CSS custom properties in :root and .dark
 * - @theme definition registering semantic design tokens with Tailwind v4
 * - Keyframes and animation helper classes
 */
export function compileTokensToCss(tokenData: DesignTokens = tokens): string {
  const { colors, typography, motion } = tokenData;

  const lightSemantic = colors.semantic.light;
  const darkSemantic = colors.semantic.dark;
  const lightSyntax = colors.syntax.light;
  const darkSyntax = colors.syntax.dark;

  const lines: string[] = [
    "/* ========================================================================= */",
    "/* AUTO-GENERATED BY SCRATCH MASTER TOKEN ENGINE — DO NOT EDIT MANUALLY      */",
    "/* Source of truth: src/tokens/tokens.ts                                    */",
    "/* ========================================================================= */",
    "",
    "/* ------------------------------------------------------------------------- */",
    "/* Light Mode Token Values (:root)                                           */",
    "/* ------------------------------------------------------------------------- */",
    ":root {",
    "  /* Modern Semantic Surfaces */",
    `  --color-surface-primary: ${lightSemantic["surface-primary"]};`,
    `  --color-surface-secondary: ${lightSemantic["surface-secondary"]};`,
    `  --color-surface-muted: ${lightSemantic["surface-muted"]};`,
    `  --color-surface-emphasis: ${lightSemantic["surface-emphasis"]};`,
    "",
    "  /* Modern Semantic Content */",
    `  --color-content-primary: ${lightSemantic["content-primary"]};`,
    `  --color-content-muted: ${lightSemantic["content-muted"]};`,
    `  --color-content-inverse: ${lightSemantic["content-inverse"]};`,
    "",
    "  /* Modern Semantic Borders & Accents */",
    `  --color-border-default: ${lightSemantic["border-default"]};`,
    `  --color-accent-primary: ${lightSemantic["accent-primary"]};`,
    `  --color-accent-selection: ${lightSemantic["accent-selection"]};`,
    "",
    "  /* Braun Signal Accents */",
    `  --color-braun-yellow: ${colors.braun.yellow};`,
    `  --color-braun-orange: ${colors.braun.orange.light};`,
    `  --color-braun-green: ${colors.braun.green.light};`,
    `  --color-braun-blue: ${colors.braun.blue.light};`,
    "",
    "  /* Backward Compatibility Aliases (maps legacy keys to modern tokens) */",
    "  --color-bg: var(--color-surface-primary);",
    "  --color-bg-secondary: var(--color-surface-secondary);",
    "  --color-bg-muted: var(--color-surface-muted);",
    "  --color-bg-emphasis: var(--color-surface-emphasis);",
    "  --color-text: var(--color-content-primary);",
    "  --color-text-muted: var(--color-content-muted);",
    "  --color-text-inverse: var(--color-content-inverse);",
    "  --color-border: var(--color-border-default);",
    "  --color-accent: var(--color-accent-primary);",
    "  --color-selection: var(--color-accent-selection);",
    "",
    "  /* Editor Font Defaults */",
    `  --editor-font-family: ${typography.fonts.sans};`,
    `  --editor-base-font-size: ${typography.editorDefaults.baseFontSize}px;`,
    `  --editor-bold-weight: ${typography.editorDefaults.boldWeight};`,
    `  --editor-line-height: ${typography.editorDefaults.lineHeight};`,
    `  --editor-paragraph-spacing: ${typography.editorDefaults.paragraphSpacing};`,
    "",
    "  /* Computed Heading Sizes */",
    `  --editor-h1-size: ${typography.editorDefaults.baseFontSize * 2.25}px;`,
    `  --editor-h2-size: ${typography.editorDefaults.baseFontSize * 1.75}px;`,
    `  --editor-h3-size: ${typography.editorDefaults.baseFontSize * 1.5}px;`,
    `  --editor-h4-size: ${typography.editorDefaults.baseFontSize * 1.25}px;`,
    `  --editor-h5-size: ${typography.editorDefaults.baseFontSize}px;`,
    `  --editor-h6-size: ${typography.editorDefaults.baseFontSize}px;`,
    "",
    "  /* Syntax Highlighting (Light) */",
    `  --color-syntax-keyword: ${lightSyntax.keyword};`,
    `  --color-syntax-string: ${lightSyntax.string};`,
    `  --color-syntax-number: ${lightSyntax.number};`,
    `  --color-syntax-comment: ${lightSyntax.comment};`,
    `  --color-syntax-function: ${lightSyntax.function};`,
    `  --color-syntax-variable: ${lightSyntax.variable};`,
    `  --color-syntax-type: ${lightSyntax.type};`,
    `  --color-syntax-operator: ${lightSyntax.operator};`,
    `  --color-syntax-attr: ${lightSyntax.attr};`,
    `  --color-code: ${lightSyntax.code};`,
    "}",
    "",
    "/* ------------------------------------------------------------------------- */",
    "/* Dark Mode Token Values (.dark)                                            */",
    "/* ------------------------------------------------------------------------- */",
    ".dark {",
    "  /* Modern Semantic Surfaces */",
    `  --color-surface-primary: ${darkSemantic["surface-primary"]};`,
    `  --color-surface-secondary: ${darkSemantic["surface-secondary"]};`,
    `  --color-surface-muted: ${darkSemantic["surface-muted"]};`,
    `  --color-surface-emphasis: ${darkSemantic["surface-emphasis"]};`,
    "",
    "  /* Modern Semantic Content */",
    `  --color-content-primary: ${darkSemantic["content-primary"]};`,
    `  --color-content-muted: ${darkSemantic["content-muted"]};`,
    `  --color-content-inverse: ${darkSemantic["content-inverse"]};`,
    "",
    "  /* Modern Semantic Borders & Accents */",
    `  --color-border-default: ${darkSemantic["border-default"]};`,
    `  --color-accent-primary: ${darkSemantic["accent-primary"]};`,
    `  --color-accent-selection: ${darkSemantic["accent-selection"]};`,
    "",
    "  /* Braun Signal Accents */",
    `  --color-braun-yellow: ${colors.braun.yellow};`,
    `  --color-braun-orange: ${colors.braun.orange.dark};`,
    `  --color-braun-green: ${colors.braun.green.dark};`,
    `  --color-braun-blue: ${colors.braun.blue.dark};`,
    "",
    "  /* Syntax Highlighting (Dark) */",
    `  --color-syntax-keyword: ${darkSyntax.keyword};`,
    `  --color-syntax-string: ${darkSyntax.string};`,
    `  --color-syntax-number: ${darkSyntax.number};`,
    `  --color-syntax-comment: ${darkSyntax.comment};`,
    `  --color-syntax-function: ${darkSyntax.function};`,
    `  --color-syntax-variable: ${darkSyntax.variable};`,
    `  --color-syntax-type: ${darkSyntax.type};`,
    `  --color-syntax-operator: ${darkSyntax.operator};`,
    `  --color-syntax-attr: ${darkSyntax.attr};`,
    `  --color-code: ${darkSyntax.code};`,
    "}",
    "",
    "/* ------------------------------------------------------------------------- */",
    "/* Tailwind CSS v4 Theme Registration (@theme)                               */",
    "/* ------------------------------------------------------------------------- */",
    "@theme {",
    "  /* Fonts */",
    `  --font-sans: ${typography.fonts.sans};`,
    `  --font-serif: ${typography.fonts.serif};`,
    `  --font-mono: ${typography.fonts.mono};`,
    "",
    "  /* Font Sizes */",
    `  --text-2xs: ${typography.sizes["2xs"].size};`,
    `  --text-2xs--line-height: ${typography.sizes["2xs"].lineHeight};`,
    `  --text-xs: ${typography.sizes.xs.size};`,
    `  --text-xs--line-height: ${typography.sizes.xs.lineHeight};`,
    "",
    "  /* Modern Semantic Surfaces */",
    "  --color-surface-primary: var(--color-surface-primary);",
    "  --color-surface-secondary: var(--color-surface-secondary);",
    "  --color-surface-muted: var(--color-surface-muted);",
    "  --color-surface-emphasis: var(--color-surface-emphasis);",
    "",
    "  /* Modern Semantic Content */",
    "  --color-content-primary: var(--color-content-primary);",
    "  --color-content-muted: var(--color-content-muted);",
    "  --color-content-inverse: var(--color-content-inverse);",
    "",
    "  /* Modern Semantic Borders & Accents */",
    "  --color-border-default: var(--color-border-default);",
    "  --color-accent-primary: var(--color-accent-primary);",
    "  --color-accent-selection: var(--color-accent-selection);",
    "",
    "  /* Braun Signal Accents */",
    "  --color-braun-yellow: var(--color-braun-yellow);",
    "  --color-braun-orange: var(--color-braun-orange);",
    "  --color-braun-green: var(--color-braun-green);",
    "  --color-braun-blue: var(--color-braun-blue);",
    "",
    "  /* Legacy Aliases */",
    "  --color-bg: var(--color-surface-primary);",
    "  --color-bg-secondary: var(--color-surface-secondary);",
    "  --color-bg-muted: var(--color-surface-muted);",
    "  --color-bg-emphasis: var(--color-surface-emphasis);",
    "  --color-text: var(--color-content-primary);",
    "  --color-text-muted: var(--color-content-muted);",
    "  --color-text-inverse: var(--color-content-inverse);",
    "  --color-border: var(--color-border-default);",
    "  --color-accent: var(--color-accent-primary);",
    "  --color-selection: var(--color-accent-selection);",
    "",
    "  /* Animations */",
    `  --animate-fade-in: ${motion.animations["fade-in"]};`,
    `  --animate-slide-down: ${motion.animations["slide-down"]};`,
    `  --animate-spin-slow: ${motion.animations["spin-slow"]};`,
    `  --animate-bounce-gentle: ${motion.animations["bounce-gentle"]};`,
    `  --animate-pulse-gentle: ${motion.animations["pulse-gentle"]};`,
    `  --animate-fade-in-up: ${motion.animations["fade-in-up"]};`,
    "}",
    "",
    "/* ------------------------------------------------------------------------- */",
    "/* Keyframes & Motion Helpers                                                */",
    "/* ------------------------------------------------------------------------- */",
  ];

  for (const [name, keyframeDef] of Object.entries(motion.keyframes)) {
    lines.push(`@keyframes ${name} {`);
    for (const [stage, rules] of Object.entries(keyframeDef)) {
      lines.push(`  ${stage} {`);
      for (const [prop, val] of Object.entries(rules)) {
        lines.push(`    ${prop}: ${val};`);
      }
      lines.push("  }");
    }
    lines.push("}");
    lines.push("");
  }

  lines.push("/* Utility classes for animations */");
  for (const [name, anim] of Object.entries(motion.animations)) {
    lines.push(`.animate-${name} {`);
    lines.push(`  animation: ${anim};`);
    lines.push("}");
  }
  lines.push("");

  return lines.join("\n");
}
